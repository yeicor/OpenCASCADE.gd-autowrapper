# Nested struct returns (Geom_*::ResD{0,1,2,3}) are packed into a Godot Array of
# wrapped gp values. Parent class -> (point wrapper type, vec wrapper type).
RESD_3D_PARENTS = {"Geom_Curve", "Geom_Surface"}
RESD_2D_PARENTS = {"Geom2d_Curve", "Geom2d_Surface"}
RESD_PARENTS = RESD_3D_PARENTS | RESD_2D_PARENTS


def resd_members(base_name: str):
    """If base_name is a Geom_*::ResD{0,1,2,3} nested struct, return the list of
    (occt_member_type, member_name) pairs it contains, else None.

    Curve structs carry D1/D2/D3; surface structs carry D1U/D1V, D2U/D2V, ..."""
    if "::ResD" not in base_name:
        return None
    parent, _, rest = base_name.partition("::")
    if parent in RESD_3D_PARENTS:
        point_type, vec_type = "gp_Pnt", "gp_Vec"
    elif parent in RESD_2D_PARENTS:
        point_type, vec_type = "gp_Pnt2d", "gp_Vec2d"
    else:
        return None
    num = int(rest.replace("ResD", ""))
    members = [(point_type, "Point")]
    if parent in ("Geom_Surface", "Geom2d_Surface"):
        for i in range(1, num + 1):
            members.append((vec_type, "D{}U".format(i)))
            members.append((vec_type, "D{}V".format(i)))
    else:
        for i in range(1, num + 1):
            members.append((vec_type, "D{}".format(i)))
    return members


def resd_members_for_type(otype: OCCTType):
    """Resolve a ResD nested struct return type to its members, trying the
    base_name, canonical spelling, and raw spelling (libclang may report just
    'ResD1' as base_name, losing the parent class that picks 2d vs 3d)."""
    for candidate in (otype.base_name, otype.canonical_spelling or "",
                      otype.spelling.replace("&", "").strip()):
        members = resd_members(candidate)
        if members:
            return members
    return None

